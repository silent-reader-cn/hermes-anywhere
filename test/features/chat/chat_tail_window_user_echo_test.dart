  const userText =
      '【我们都是奶蛙，有一天会被正义的奶龙杀死-哔哩哔哩】 https://b23.tv/khUOtGV '
      '把这个也收集进入我们的灵感库 ，把一些类似跑酷失败这种视频 换成沮丧的奶龙这种抽象角色 。'
      '这样用户看着不惨反而搞笑。因为人对这种抽象角色其实是没有同情心的';

  List<ChatMessage> buildAllLoaded() {
    final out = <ChatMessage>[];
    for (var i = 0; i < transcript.length; i++) {
      final (role, ts) = transcript[i];
      final dartRole = switch (role) {
        'u' => 'user',
        'a' => 'assistant',
        _ => 'tool',
      };
      out.add(
        ChatMessage(
          role: dartRole,
          content: role == 'u' ? userText : 'row-$i',
          messageId: 'm-$i',
          toolCallId: role == 't' ? 'call-$i' : null,
          timestamp: ts,
        ),
      );
    }
    return out;
  }

  test('尾窗确实把提问行裁在窗口外（起点 > 0 且窗口内无 user 行）', () {
    final all = buildAllLoaded();
    final window = ChatController.tailWindowRangeForTesting(all, 50);
    expect(
      window.start,
      greaterThan(0),
      reason: '该会话可渲染行多于 50，必然裁窗',
    );
    expect(
      window.rows.any((m) => m.role == 'user'),
      isFalse,
      reason: '窗口内没有任何 user 回合边界 —— 这正是插入点退化的前提',
    );
  });

  test('回合收尾不得把本轮提问气泡插到回复末尾', () {
    final all = buildAllLoaded();
    final window = ChatController.tailWindowRangeForTesting(all, 50);

    // 回合结束瞬间的本地状态：发送时的乐观提问行 + 流式 assistant 行。
    final localUser = ChatMessage(
      role: 'user',
      content: userText,
      messageId: 'local-optimistic',
      timestamp: transcript.first.$2,
    );
    final streaming = ChatMessage(
      role: 'assistant',
      content: '收好了喵——这条已经成了库里新系列的开山大样本。',
      messageId: 'stream-live',
      timestamp: transcript.last.$2,
    );

    final merged = ChatController.mergingLoadedMessagesForTesting(
      window.rows,
      [localUser, streaming],
      streamingMessageId: 'stream-live',
    );

    expect(
      merged.last.role,
      isNot('user'),
      reason: '回合收尾后最后一条不得是用户气泡（0.1.81 真机现象）',
    );
    expect(
      merged.any((m) => (m.messageId ?? '').startsWith('local-')),
      isFalse,
      reason: '提问行已落在窗口外 ⇒ 属陈旧回声，不得插回本轮',
    );
    expect(
      merged.where((m) => m.role == 'user'),
      isEmpty,
      reason: '窗口外的提问行由「加载更多」历史页提供，不能由收尾合并伪造一份',
    );
  });
